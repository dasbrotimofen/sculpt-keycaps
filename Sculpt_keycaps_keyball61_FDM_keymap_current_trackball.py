def _step(n: int, i: int) -> float:

    half = (n - 1) * 0.5
    return (i - half) / half if half != 0 else 0.0


def _sin_extend(a: float) -> float:

    if abs(a) > 90:
        return round(a / 90.0) + math.sin(math.radians(a % 90))
    return math.sin(math.radians(a))


def _asin_extend(r: float) -> float:

    if abs(r) > 1:
        return 90.0 * round(r) + math.degrees(math.asin(r % 1))
    return math.degrees(math.asin(r))


def _bias_ratio(a: float, s: float) -> float:

    if a == 0 or s == 0:
        return 1.0
    if abs(a) > abs(s):
        return abs(s / a) * _sign(s)
    return abs(a / s) * _sign(s)


def _bias_degrees(r: float, a: float, s: float) -> float:

    mag = abs(s * _bias_ratio(a, s))
    return mag * _sign(r) if abs(r * a) > abs(s) else mag * _sign(s)


def _ratio_range(a: float, s: float) -> float:

    return abs(a) + abs(s)


def _ratio_degrees(r: float, a: float, s: float) -> float:

    return _asin_extend(r) * (_ratio_range(a, s) / 90.0) + _bias_degrees(r, a, s)


def _ratio_sin(r: float, e: float = 1.0, a: float = 0.0, s: float = 0.0) -> float:


    rd = _ratio_degrees(r, a, s)
    se = _sin_extend(rd)
    return abs(se) ** e * _sign(r)


def _step_smooth_2(n: int, i: int) -> Tuple[int, int, int]:

    if i == 0:
        return (0, 0, 0)
    if i == n - 1:
        return (n - 1, n - 1, n - 1)
    return (i - 1, i, i + 1)


def _step_angle(n: int, a: float, s: float, i: int) -> float:

    return -_ratio_sin(_step(n, i), 1.0, a, s)


def _step_height(n: int, a: float, s: float, i: int) -> float:

    return abs(_ratio_sin(_step(n, i), 1.0, a, s))


def _step_angle_smoothed(n: int, a: float, s: float, i: int) -> float:

    p = _step_smooth_2(n, i)
    return (_step_angle(n, a, s, p[0]) * 0.33
            + _step_angle(n, a, s, p[1]) * 0.33
            + _step_angle(n, a, s, p[2]) * 0.33)


def _step_height_smoothed(n: int, a: float, s: float, i: int) -> float:

    p = _step_smooth_2(n, i)
    return (_step_height(n, a, s, p[0]) * 0.25
            + _step_height(n, a, s, p[1]) * 0.5
            + _step_height(n, a, s, p[2]) * 0.25)


def single_axis_sweep(height: Tuple[float, float], sweep_angle: float,
                      sweep_shift: float, slices: int) -> List[Tuple[float, float]]:

    result: List[Tuple[float, float]] = []
    for i in range(slices):
        ang = _step_angle_smoothed(slices, sweep_angle, sweep_shift, i) * sweep_angle
        h = (_step_height_smoothed(slices, sweep_angle, sweep_shift, i)
             * (height[0] - height[1]) + height[1])
        result.append((ang, h))
    return result


def dual_axis_sweep(height: Tuple[float, float],
                    sweep_angle: Tuple[float, float],
                    sweep_shift: Tuple[float, float],
                    slices: Tuple[int, int]) -> list:


    axis_a = single_axis_sweep(height, sweep_angle[0], sweep_shift[0], slices[0])
    axis_b = single_axis_sweep(height, sweep_angle[1], sweep_shift[1], slices[1])
    design = []
    for a_ang, a_h in axis_a:
        col = []
        for b_ang, b_h in axis_b:
            ax = a_ang * 0.9 + abs(b_ang) * 0.1 * _sign(a_ang)
            ay = b_ang * 0.9 + abs(a_ang) * 0.1 * _sign(b_ang)
            ch = height[1] + (a_h + b_h - height[1] * 2)
            col.append(((ax, ay), ch))
        design.append(col)
    return design


